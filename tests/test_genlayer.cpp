namespace {
void check_eq(const std::vector<std::int32_t>& got, const std::int32_t* want, std::size_t n) {
  REQUIRE(got.size() == n);
  for (std::size_t i = 0; i < n; ++i) {
    if (got[i] != want[i]) {
      INFO("mismatch at " << i << ": got " << got[i] << " want " << want[i]);
      CHECK(got[i] == want[i]);
    }
  }
}
}  // namespace

